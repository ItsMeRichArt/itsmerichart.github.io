let publicRepositories = null;

function preferredLanguage() {
  const fromUrl = new URL(window.location.href).searchParams.get("lang");
  if (fromUrl === "en" || fromUrl === "es") return fromUrl;
  try {
    const saved = localStorage.getItem("portfolio-language");
    if (saved === "en" || saved === "es") return saved;
  } catch { /* Browsers may disable storage. */ }
  return "en";
}

function setLanguage(language, updateAddress = false) {
  const strings = copy[language] || copy.en;
  document.documentElement.lang = language;
  document.title = strings["page.title"];
  document.querySelector('meta[name="description"]').content = strings["page.description"];
  document.querySelector('meta[property="og:description"]').content = strings["page.ogDescription"];
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = strings[node.dataset.i18n];
    if (value !== undefined) node.textContent = value;
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((node) => {
    const value = strings[node.dataset.i18nAlt];
    if (value !== undefined) node.alt = value;
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    const value = strings[node.dataset.i18nAriaLabel];
    if (value !== undefined) node.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === language));
  });
  document.querySelector(".kurius-links a").href = `https://www.kuriuschocolate.com/${language}`;
  renderRepositories(language);
  try { localStorage.setItem("portfolio-language", language); } catch { /* Optional preference. */ }
  if (updateAddress) {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", language);
    history.replaceState(null, "", url);
  }
}

function renderRepositories(language) {
  if (!publicRepositories) return;
  const strings = copy[language];
  const list = document.getElementById("repo-list");
  const repos = publicRepositories
    .filter((repo) => !repo.fork && !["itsmerichart", "itsmerichart.github.io"].includes(repo.name.toLowerCase()))
    .sort((a, b) => Number(a.archived) - Number(b.archived) || a.name.localeCompare(b.name));

  document.getElementById("repo-count").textContent = String(repos.length);
  list.replaceChildren();
  for (const repo of repos) {
    const link = document.createElement("a");
    link.className = "repo-link";
    link.href = repo.html_url;
    link.target = "_blank";
    link.rel = "noopener noreferrer";

    const heading = document.createElement("div");
    heading.className = "repo-link-head";
    const name = document.createElement("strong");
    name.textContent = repo.name;
    const badge = document.createElement("span");
    badge.textContent = repo.archived ? strings["projects.archiveStatus"] : strings["projects.currentStatus"];
    heading.append(name, badge);

    const subline = document.createElement("p");
    subline.textContent = repo.language || strings["projects.noLanguage"];
    link.append(heading, subline);
    list.append(link);
  }
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang, true));
});
document.getElementById("year").textContent = String(new Date().getFullYear());
setLanguage(preferredLanguage());

fetch("data/public-repositories.json")
  .then((response) => {
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    return response.json();
  })
  .then((repositories) => {
    publicRepositories = repositories;
    renderRepositories(document.documentElement.lang);
  })
  .catch(() => {
    const list = document.getElementById("repo-list");
    list.replaceChildren();
    const fallback = document.createElement("a");
    fallback.href = "https://github.com/ItsMeRichArt?tab=repositories";
    fallback.target = "_blank";
    fallback.rel = "noopener noreferrer";
    fallback.textContent = copy[document.documentElement.lang]["projects.loadError"];
    list.append(fallback);
  });
